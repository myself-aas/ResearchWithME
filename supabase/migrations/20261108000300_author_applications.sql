-- Writer applications.
--
-- Sign-in (email + password, or Google) creates an account. Publishing needs a
-- row in public.editors. This table is the bridge: a signed-in reader links a
-- scholarly identity (GitHub or ORCID) to their account and submits an
-- application, which an existing editor approves or rejects. Approval writes the
-- allowlist row, so access is granted by a person and never self-asserted.
--
-- Idempotent: safe to re-run.

begin;

create table if not exists public.author_applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  provider text not null,
  handle text not null,
  display_name text not null,
  statement text not null default '',
  status text not null default 'pending',
  reviewed_by uuid references auth.users (id) on delete set null,
  reviewed_at timestamptz,
  review_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint author_applications_provider check (provider in ('github', 'orcid')),
  constraint author_applications_status check (status in ('pending', 'approved', 'rejected')),
  constraint author_applications_handle check (char_length(handle) between 1 and 160),
  constraint author_applications_name check (char_length(display_name) between 1 and 120),
  constraint author_applications_statement check (char_length(statement) <= 1000),
  constraint author_applications_note check (char_length(review_note) <= 500),
  constraint author_applications_reviewed
    check (
      (status = 'pending' and reviewed_at is null and reviewed_by is null)
      or (status <> 'pending' and reviewed_at is not null)
    )
);

-- One linked identity per provider per account.
drop index if exists public.author_applications_user_provider_key;
create unique index if not exists author_applications_user_provider_key
  on public.author_applications (user_id, provider);

-- At most one open application per account, so resubmitting updates in place.
drop index if exists public.author_applications_one_pending;
create unique index if not exists author_applications_one_pending
  on public.author_applications (user_id)
  where status = 'pending';

drop index if exists public.author_applications_status_created_at;
create index if not exists author_applications_status_created_at
  on public.author_applications (status, created_at);

alter table public.author_applications enable row level security;

-- Readers see their own applications; editors see the queue. There are no
-- insert, update, or delete policies: every write goes through the functions
-- below, which check the caller.
drop policy if exists "Users can see their own applications" on public.author_applications;
create policy "Users can see their own applications"
  on public.author_applications for select
  to authenticated
  using (user_id = (select auth.uid()) or public.is_editor());

revoke all on public.author_applications from anon, authenticated;
grant select on public.author_applications to authenticated;

-- Submit or update the caller's own application.
--
-- SECURITY DEFINER because the table has no insert policy. It only ever writes
-- the caller's own row, and refuses anyone who is already an editor.
create or replace function public.apply_as_author(
  p_provider text,
  p_handle text,
  p_display_name text,
  p_statement text default ''
)
returns public.author_applications
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller uuid := (select auth.uid());
  result public.author_applications;
begin
  if caller is null then
    raise exception 'not_authenticated';
  end if;
  if p_provider not in ('github', 'orcid') then
    raise exception 'unsupported_provider';
  end if;
  if char_length(btrim(coalesce(p_handle, ''))) = 0 then
    raise exception 'handle_required';
  end if;
  if char_length(btrim(coalesce(p_display_name, ''))) = 0 then
    raise exception 'name_required';
  end if;
  if exists (select 1 from public.editors e where e.user_id = caller) then
    raise exception 'already_editor';
  end if;

  insert into public.author_applications (
    user_id, provider, handle, display_name, statement
  )
  values (
    caller,
    p_provider,
    left(btrim(p_handle), 160),
    left(btrim(p_display_name), 120),
    left(coalesce(p_statement, ''), 1000)
  )
  on conflict (user_id, provider) do update set
    handle = excluded.handle,
    display_name = excluded.display_name,
    statement = excluded.statement,
    -- A rejected applicant may reapply; an approved or pending one keeps its state.
    status = case
      when public.author_applications.status = 'rejected' then 'pending'
      else public.author_applications.status
    end,
    reviewed_by = null,
    reviewed_at = null,
    review_note = '',
    updated_at = now()
  returning * into result;

  return result;
end;
$$;

-- Approve or reject an application. Approval grants studio access.
create or replace function public.review_author_application(
  p_id bigint,
  p_approve boolean,
  p_note text default ''
)
returns public.author_applications
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller uuid := (select auth.uid());
  applicant uuid;
  result public.author_applications;
begin
  if caller is null then
    raise exception 'not_authenticated';
  end if;
  if not public.is_editor() then
    raise exception 'not_editor';
  end if;

  select a.user_id into applicant
  from public.author_applications a
  where a.id = p_id
  for update;

  if applicant is null then
    raise exception 'not_found';
  end if;

  update public.author_applications
  set status = case when p_approve then 'approved' else 'rejected' end,
      reviewed_by = caller,
      reviewed_at = now(),
      review_note = left(coalesce(p_note, ''), 500),
      updated_at = now()
  where id = p_id
  returning * into result;

  if p_approve then
    insert into public.editors (user_id, note)
    values (applicant, left('Approved via ' || result.provider || ' application', 200))
    on conflict (user_id) do nothing;
  end if;

  return result;
end;
$$;

revoke all on function public.apply_as_author(text, text, text, text) from public, anon;
grant execute on function public.apply_as_author(text, text, text, text) to authenticated;

revoke all on function public.review_author_application(bigint, boolean, text) from public, anon;
grant execute on function public.review_author_application(bigint, boolean, text) to authenticated;

commit;
