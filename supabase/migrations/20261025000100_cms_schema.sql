-- ResearchWithMe editorial CMS
-- Step 1 of the Supabase blueprint: tables, integrity rules, RLS, realtime.
--
-- Design notes (deliberate hardening over the reference blueprint):
--   * Drafts may be incomplete; the published-state requirement is enforced by a
--     check constraint instead of forcing every draft to be publish-ready.
--   * `posts` keeps the blueprint's columns and adds the publication metadata the
--     ResearchWithMe reader already renders (summary, category, byline, tags...).
--   * `comments` are append-only for the public: nobody can update them, and only
--     authenticated editors can delete them.
--   * RLS is enabled on every table. Anonymous visitors can only read published
--     posts and can only insert comments that satisfy the length constraints.
--   * updated_at / published_at are maintained by triggers so the API cannot drift.
--
-- Apply with `supabase db push` or paste the file into the Supabase SQL editor.

begin;

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null,
  content text not null default '',
  status text not null default 'draft',
  subtitle text not null default '',
  summary text not null default '',
  category text not null default 'Research Reviews',
  format text not null default 'Paper Review',
  author_id text,
  author_name text not null default 'ResearchWithMe editors',
  cover_image text,
  tags text[] not null default '{}',
  key_takeaways text[] not null default '{}',
  read_time text not null default '6 min read',
  featured boolean not null default false,
  likes integer not null default 0,
  published_at timestamptz,
  inserted_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint posts_title_length check (char_length(title) between 1 and 180),
  constraint posts_slug_format check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) between 1 and 96),
  constraint posts_slug_unique unique (slug),
  constraint posts_content_length check (char_length(content) <= 200000),
  constraint posts_summary_length check (char_length(summary) <= 1200),
  constraint posts_subtitle_length check (char_length(subtitle) <= 400),
  constraint posts_author_name_length check (char_length(author_name) between 1 and 120),
  constraint posts_tags_length check (cardinality(tags) <= 8),
  constraint posts_takeaways_length check (cardinality(key_takeaways) <= 8),
  constraint posts_likes_non_negative check (likes >= 0),
  constraint posts_status_allowed check (status in ('draft', 'published')),
  -- A row may be an unfinished draft, but it cannot be published until it is a
  -- complete article. This keeps public output trustworthy without blocking work
  -- in progress.
  constraint posts_publish_ready check (
    status <> 'published'
    or (
      char_length(title) >= 8
      and char_length(content) >= 200
      and char_length(summary) >= 40
    )
  )
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts (id) on delete cascade,
  author_name text not null default 'Reader',
  author_role text not null default 'Reader',
  content text not null,
  inserted_at timestamptz not null default timezone('utc', now()),
  constraint comments_author_name_length check (char_length(author_name) between 1 and 120),
  constraint comments_author_role_length check (char_length(author_role) <= 80),
  constraint comments_content_length check (char_length(content) between 2 and 4000)
);

create index if not exists posts_status_published_at_idx
  on public.posts (status, published_at desc nulls last);
create index if not exists posts_author_id_idx on public.posts (author_id);
create index if not exists posts_inserted_at_idx on public.posts (inserted_at desc);
create index if not exists comments_post_id_inserted_at_idx
  on public.comments (post_id, inserted_at);
create index if not exists comments_inserted_at_idx on public.comments (inserted_at desc);

-- Keep timestamps authoritative on the server.
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.stamp_published_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.status = 'published' and new.published_at is null then
    new.published_at = now();
  elsif new.status = 'draft' then
    new.published_at = null;
  end if;
  return new;
end;
$$;

drop trigger if exists posts_touch_updated_at on public.posts;
create trigger posts_touch_updated_at
  before insert or update on public.posts
  for each row execute function public.touch_updated_at();

drop trigger if exists posts_stamp_published_at on public.posts;
create trigger posts_stamp_published_at
  before insert or update on public.posts
  for each row execute function public.stamp_published_at();

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
alter table public.posts enable row level security;
alter table public.comments enable row level security;

drop policy if exists "Published posts are publicly readable" on public.posts;
create policy "Published posts are publicly readable"
  on public.posts for select
  to anon, authenticated
  using (status = 'published');

drop policy if exists "Editors can read every post" on public.posts;
create policy "Editors can read every post"
  on public.posts for select
  to authenticated
  using (true);

drop policy if exists "Editors can create posts" on public.posts;
create policy "Editors can create posts"
  on public.posts for insert
  to authenticated
  with check (true);

drop policy if exists "Editors can update posts" on public.posts;
create policy "Editors can update posts"
  on public.posts for update
  to authenticated
  using (true)
  with check (true);

drop policy if exists "Editors can delete posts" on public.posts;
create policy "Editors can delete posts"
  on public.posts for delete
  to authenticated
  using (true);

-- Readers only see discussion attached to a published article. Editors get a
-- second policy so the moderation queue can include drafts.
drop policy if exists "Published comments are publicly readable" on public.comments;
create policy "Published comments are publicly readable"
  on public.comments for select
  to anon
  using (
    exists (
      select 1 from public.posts p
      where p.id = post_id and p.status = 'published'
    )
  );

drop policy if exists "Editors can read all comments" on public.comments;
create policy "Editors can read all comments"
  on public.comments for select
  to authenticated
  using (true);

-- Public comment creation stays possible, but only within the same limits the
-- application enforces. Rate limiting and origin checks live in the API route;
-- add a CAPTCHA or edge rate limit before opening comments to high traffic.
drop policy if exists "Anyone can post a comment" on public.comments;
create policy "Anyone can post a comment"
  on public.comments for insert
  to anon, authenticated
  with check (
    char_length(content) between 2 and 4000
    and char_length(author_name) between 1 and 120
    and char_length(author_role) <= 80
    and exists (
      select 1 from public.posts p
      where p.id = post_id and p.status = 'published'
    )
  );

drop policy if exists "Editors can delete comments" on public.comments;
create policy "Editors can delete comments"
  on public.comments for delete
  to authenticated
  using (true);

-- Comments are append-only: no update policy exists, so updates are denied for
-- every role, including authenticated editors.

-- Likes are a soft signal, so a narrowly scoped SECURITY DEFINER function is
-- enough: it can only touch one counter on a published post, and the public API
-- route applies per-IP rate limiting before calling it.
create or replace function public.increment_post_likes(target_id bigint)
returns integer
language sql
security definer
set search_path = 'public'
as $$
  update public.posts
  set likes = likes + 1
  where id = target_id and status = 'published'
  returning likes;
$$;

revoke all on function public.increment_post_likes(bigint) from public;
grant execute on function public.increment_post_likes(bigint) to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Privileges (RLS still decides which rows are visible)
-- ---------------------------------------------------------------------------
grant usage on schema public to anon, authenticated;
grant select on public.posts to anon, authenticated;
grant insert, update, delete on public.posts to authenticated;
grant select, insert on public.comments to anon, authenticated;
grant delete on public.comments to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Realtime replication
-- ---------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'posts'
    ) then
      execute 'alter publication supabase_realtime add table public.posts';
    end if;

    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'comments'
    ) then
      execute 'alter publication supabase_realtime add table public.comments';
    end if;
  end if;
end;
$$;

commit;
