-- Billing: what a customer bought, and the one privileged path that records it.
--
-- Lemon Squeezy is the merchant of record and the authority on purchases. This
-- schema is a mirror of what it tells us, plus the audit trail of what it told
-- us. Nothing here prices anything and nothing here charges anybody.
--
-- The shape is driven by one constraint: the webhook has no user session. Every
-- other write in this codebase is a user acting on their own rows, which a
-- policy expresses directly (see 20261108000400_author_profiles.sql). Here the
-- caller is Lemon Squeezy's server, using the same publishable key the browser
-- uses, so RLS has nobody to scope to. The answer is one security-definer
-- function that only acts when it is given the bridge secret, called with the
-- anon key. The app still ships no service-role key, which is the property
-- docs/codebase/CONCERNS.md and README.md both depend on.
--
-- Reading is ordinary: one `auth.uid() = user_id` policy per user table, no
-- insert/update/delete policy anywhere. The bridge function is the only writer.
-- Billing events have no policy at all and no grant, so they are invisible to
-- every API caller -- an audit table, not an API.
--
-- Idempotent: safe to re-run.

begin;

-- ---------------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------------

create table if not exists public.billing_customers (
  user_id uuid primary key references auth.users (id) on delete cascade,
  lemon_customer_id text not null,
  email text not null default '',
  test_mode boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint billing_customers_lemon_id_key unique (lemon_customer_id),
  constraint billing_customers_email_length check (char_length(email) <= 254)
);

create table if not exists public.billing_orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  lemon_order_id text not null,
  lemon_customer_id text not null default '',
  variant_id text not null default '',
  product_name text not null default '',
  -- Integer cents, in the order currency. Lemon Squeezy sends integers; a
  -- numeric column would invite a rounding decision this app has no business making.
  total integer not null default 0,
  currency text not null default 'USD',
  status text not null default 'paid',
  ai_credits integer not null default 0,
  test_mode boolean not null default false,
  occurred_at timestamptz not null default now(),
  inserted_at timestamptz not null default now(),

  constraint billing_orders_lemon_id_key unique (lemon_order_id),
  constraint billing_orders_total_non_negative check (total >= 0),
  constraint billing_orders_credits_non_negative check (ai_credits >= 0),
  constraint billing_orders_status_length check (char_length(status) between 1 and 40),
  constraint billing_orders_currency_length check (char_length(currency) = 3)
);

create table if not exists public.billing_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  lemon_subscription_id text not null,
  lemon_customer_id text not null default '',
  variant_id text not null default '',
  status text not null,
  renews_at timestamptz,
  ends_at timestamptz,
  test_mode boolean not null default false,
  occurred_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint billing_subscriptions_lemon_id_key unique (lemon_subscription_id),
  -- Lemon Squeezy's own vocabulary. `none` is deliberately absent: a row exists
  -- only once a subscription does.
  constraint billing_subscriptions_status_allowed check (
    status in ('on_trial', 'active', 'paused', 'past_due', 'unpaid', 'cancelled', 'expired')
  )
);

create table if not exists public.billing_events (
  event_id text primary key,
  event_name text not null,
  user_id uuid,
  outcome text not null,
  note text not null default '',
  received_at timestamptz not null default now(),

  constraint billing_events_outcome_allowed check (outcome in ('applied', 'duplicate', 'ignored')),
  constraint billing_events_id_length check (char_length(event_id) between 1 and 200)
);

create index if not exists billing_orders_user_id_idx on public.billing_orders (user_id, occurred_at desc);
create index if not exists billing_subscriptions_user_id_idx on public.billing_subscriptions (user_id, updated_at desc);
create index if not exists billing_events_received_at_idx on public.billing_events (received_at desc);

-- ---------------------------------------------------------------------------
-- 2. Row Level Security
-- ---------------------------------------------------------------------------

alter table public.billing_customers enable row level security;
alter table public.billing_orders enable row level security;
alter table public.billing_subscriptions enable row level security;
alter table public.billing_events enable row level security;

drop policy if exists "Customers can read their own billing record" on public.billing_customers;
create policy "Customers can read their own billing record"
  on public.billing_customers for select
  to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Customers can read their own orders" on public.billing_orders;
create policy "Customers can read their own orders"
  on public.billing_orders for select
  to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Customers can read their own subscription" on public.billing_subscriptions;
create policy "Customers can read their own subscription"
  on public.billing_subscriptions for select
  to authenticated
  using (user_id = (select auth.uid()));

-- billing_events: no policy, and no grant below. Editors do not read it either;
-- a support question about a delivery is answered from the Lemon Squeezy
-- dashboard, which is the system of record for deliveries.

revoke all on public.billing_customers from anon;
revoke all on public.billing_orders from anon;
revoke all on public.billing_subscriptions from anon;
revoke all on public.billing_events from anon, authenticated;

grant select on public.billing_customers to authenticated;
grant select on public.billing_orders to authenticated;
grant select on public.billing_subscriptions to authenticated;

-- ---------------------------------------------------------------------------
-- 3. The bridge secret
-- ---------------------------------------------------------------------------

create schema if not exists private;
revoke all on schema private from anon, authenticated;

create table if not exists private.billing_settings (
  key text primary key,
  value text not null
);

revoke all on private.billing_settings from anon, authenticated;

-- The owner inserts the digest after this migration:
--   printf %s "$BILLING_BRIDGE_SECRET" | shasum -a 256
--   insert into private.billing_settings (key, value)
--   values ('bridge_secret_sha256', '<hex>')
--   on conflict (key) do update set value = excluded.value;
-- An absent row fails every call closed.

create or replace function public.billing_secret_matches(candidate text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  expected text;
begin
  select value into expected
    from private.billing_settings
   where key = 'bridge_secret_sha256';

  if expected is null or expected = '' then
    return false;
  end if;
  if candidate is null or candidate = '' then
    return false;
  end if;

  -- sha256(bytea) is core Postgres (11+), not pgcrypto: no extension schema to
  -- qualify and nothing to install. convert_to pins the encoding so the digest
  -- matches what `printf %s "$SECRET" | shasum -a 256` produces.
  return sha256(convert_to(candidate, 'UTF8')) = decode(expected, 'hex');
end;
$$;

revoke all on function public.billing_secret_matches(text) from public;
grant execute on function public.billing_secret_matches(text) to anon, authenticated;

-- ---------------------------------------------------------------------------
-- 4. The event bridge
-- ---------------------------------------------------------------------------
--
-- Called by /api/webhooks/lemonsqueezy with the publishable key. Three jobs, in
-- this order:
--
--   1. Refuse unless the bridge secret matches. Nothing is written before this.
--   2. Claim the event id. Lemon Squeezy retries a failed delivery up to three
--      times, so the second delivery of an event must not credit anything a
--      second time. The insert-and-check is the lock: the primary key does the
--      deduplication, not a prior select.
--   3. Apply. Orders upsert on lemon_order_id; subscriptions upsert on
--      lemon_subscription_id and take the newest status.
--
-- The caller passes a normalised payload (lib/billing/events.ts), never the
-- vendor's raw body: the mapping from JSON:API to these columns is tested in
-- TypeScript where it can be.
--
-- p_payload shape (all optional except kind):
--   kind: 'order' | 'subscription'
--   lemonCustomerId, lemonOrderId, lemonSubscriptionId, variantId, productName,
--   status, total, currency, aiCredits, testMode, occurredAt, renewsAt, endsAt

create or replace function public.apply_billing_event(
  p_bridge_secret text,
  p_event_id text,
  p_event_name text,
  p_payload jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_kind text;
  v_user_id uuid;
  v_claimed integer;
  v_occurred timestamptz;
  v_test_mode boolean;
  v_customer_id text;
begin
  if not public.billing_secret_matches(p_bridge_secret) then
    raise exception 'billing_bridge_unauthorized' using errcode = '28000';
  end if;

  v_kind := coalesce(p_payload ->> 'kind', '');
  v_user_id := nullif(p_payload ->> 'userId', '')::uuid;
  v_test_mode := coalesce((p_payload ->> 'testMode')::boolean, false);
  v_occurred := coalesce(nullif(p_payload ->> 'occurredAt', '')::timestamptz, now());
  v_customer_id := coalesce(p_payload ->> 'lemonCustomerId', '');

  -- No user id means the purchase cannot be attributed to an account. Record
  -- that it arrived and stop: an unattributable order is a support question,
  -- not an error the sender should retry.
  if v_user_id is null or v_kind not in ('order', 'subscription') then
    insert into public.billing_events (event_id, event_name, user_id, outcome, note)
    values (p_event_id, p_event_name, v_user_id, 'ignored',
            case when v_user_id is null then 'missing_user_id' else 'unhandled_kind' end)
    on conflict (event_id) do nothing;
    return jsonb_build_object('applied', false, 'duplicate', false, 'ignored', true);
  end if;

  insert into public.billing_events (event_id, event_name, user_id, outcome)
  values (p_event_id, p_event_name, v_user_id, 'applied')
  on conflict (event_id) do nothing;

  get diagnostics v_claimed = row_count;
  if v_claimed = 0 then
    return jsonb_build_object('applied', false, 'duplicate', true, 'ignored', false);
  end if;

  if v_customer_id <> '' then
    insert into public.billing_customers (user_id, lemon_customer_id, email, test_mode)
    values (v_user_id, v_customer_id, coalesce(p_payload ->> 'email', ''), v_test_mode)
    on conflict (user_id) do update
      set lemon_customer_id = excluded.lemon_customer_id,
          test_mode = excluded.test_mode,
          updated_at = now();
  end if;

  if v_kind = 'order' then
    insert into public.billing_orders (
      user_id, lemon_order_id, lemon_customer_id, variant_id, product_name,
      total, currency, status, ai_credits, test_mode, occurred_at
    )
    values (
      v_user_id,
      coalesce(p_payload ->> 'lemonOrderId', ''),
      v_customer_id,
      coalesce(p_payload ->> 'variantId', ''),
      coalesce(p_payload ->> 'productName', ''),
      coalesce((p_payload ->> 'total')::integer, 0),
      coalesce(nullif(p_payload ->> 'currency', ''), 'USD'),
      coalesce(nullif(p_payload ->> 'status', ''), 'paid'),
      coalesce((p_payload ->> 'aiCredits')::integer, 0),
      v_test_mode,
      v_occurred
    )
    on conflict (lemon_order_id) do update
      set status = excluded.status,
          total = excluded.total,
          ai_credits = excluded.ai_credits,
          test_mode = excluded.test_mode;
  else
    insert into public.billing_subscriptions (
      user_id, lemon_subscription_id, lemon_customer_id, variant_id,
      status, renews_at, ends_at, test_mode, occurred_at
    )
    values (
      v_user_id,
      coalesce(p_payload ->> 'lemonSubscriptionId', ''),
      v_customer_id,
      coalesce(p_payload ->> 'variantId', ''),
      coalesce(nullif(p_payload ->> 'status', ''), 'active'),
      nullif(p_payload ->> 'renewsAt', '')::timestamptz,
      nullif(p_payload ->> 'endsAt', '')::timestamptz,
      v_test_mode,
      v_occurred
    )
    on conflict (lemon_subscription_id) do update
      set status = excluded.status,
          variant_id = excluded.variant_id,
          renews_at = excluded.renews_at,
          ends_at = excluded.ends_at,
          test_mode = excluded.test_mode,
          occurred_at = excluded.occurred_at,
          updated_at = now();
  end if;

  return jsonb_build_object('applied', true, 'duplicate', false, 'ignored', false);
end;
$$;

revoke all on function public.apply_billing_event(text, text, text, jsonb) from public;
grant execute on function public.apply_billing_event(text, text, text, jsonb) to anon, authenticated;

commit;
