#!/usr/bin/env node
/**
 * reme token pipeline — build.
 * Source of truth: tokens/src/*.json. Emits tokens/generated/:
 *   tokens.css (light :root + system dark media + .dark class + component aliases)
 *   tokens.scss, tokens.ts, tokens.json
 * Fails on unresolved references or reference cycles.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', 'src');
const dist = join(here, '..', 'generated');
mkdirSync(dist, { recursive: true });

const read = (name) => JSON.parse(readFileSync(join(src, name), 'utf8'));
const root = {
  v4: JSON.parse(readFileSync(join(here, '../../src/generated/palette.json'), 'utf8')),
  primitive: read('primitive.json'),
  semantic: { light: read('semantic-light.json'), dark: read('semantic-dark.json') },
  motion: read('motion.json'),
  component: read('component.json'),
};

const REF = /^\{(.+)\}$/;
const resolve = (value, seen = new Set()) => {
  if (typeof value !== 'string') return value;
  const m = value.match(REF);
  if (!m) return value;
  const path = m[1];
  if (seen.has(path)) throw new Error(`Circular token reference: ${[...seen, path].join(' -> ')}`);
  const parts = path.split('.');
  let cur = root;
  for (const p of parts) {
    if (cur == null || typeof cur !== 'object' || !(p in cur)) throw new Error(`Unresolved token reference: {${path}}`);
    cur = cur[p];
  }
  return resolve(cur, new Set([...seen, path]));
};

const resolveTree = (node) => {
  if (node && typeof node === 'object') {
    return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, resolveTree(v)]));
  }
  return resolve(node);
};

const resolved = resolveTree(root);

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/_/g, '-').toLowerCase();
const flatten = (obj, prefix = []) =>
  Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object' ? flatten(v, [...prefix, kebab(k)]) : [[[...prefix, kebab(k)].join('-'), v]],
  );

const cssVars = (tree, prefix) =>
  flatten(tree).map(([path, value]) =>
    // An empty prefix emits `--reme-<path>`; a named prefix emits
    // `--reme-<prefix>-<path>`. (An earlier `--reme--<path>` double-dash
    // spelling left the primitive scales unresolvable from var() consumers.)
    `  --reme-${prefix ? `${prefix}-` : ''}${path}: ${value};`,
  ).join('\n');

// Browser aliases stay linked to semantic variables, while TS/JSON/SCSS
// retain the fully resolved literal contract used by non-browser renderers.
const componentCss = flatten(root.component).map(([path, value]) => {
  const reference = typeof value === 'string' ? value.match(REF)?.[1] : undefined;
  let variable;
  if (reference?.startsWith('semantic.light.')) {
    variable = reference.slice('semantic.light.'.length).split('.').map(kebab).join('-');
  } else if (reference && /^primitive\.(radius|space|focus|layout|icon|shadow|graph)\./.test(reference)) {
    variable = reference.slice('primitive.'.length).split('.').map(kebab).join('-');
  }
  if (reference && !variable) throw new Error(`Unsupported component CSS reference: {${reference}}`);
  return `  --reme-component-${path}: ${variable ? `var(--reme-${variable})` : resolve(value)};`;
}).join('\n');

const light = resolved.semantic.light;
const dark = resolved.semantic.dark;
const css = `/* reme v4 compatibility tokens — GENERATED by tokens/scripts/build.mjs. Do not edit by hand.
   Source: src/design palette projection + legacy tokens/src/*.json. */
:root {
${cssVars({ color: resolved.primitive.color, font: resolved.primitive.typography.family, space: resolved.primitive.space, radius: resolved.primitive.radius, shadow: resolved.primitive.shadow, layout: resolved.primitive.layout, focus: resolved.primitive.focus, icon: resolved.primitive.icon, graph: resolved.primitive.graph, motion: resolved.motion }, '')}
${flatten(light).map(([p, v]) => `  --reme-${p}: ${v};`).join('\n')}
${componentCss}
}

/* System dark theme */
@media (prefers-color-scheme: dark) {
  :root:not(.light) {
${flatten(dark).map(([p, v]) => `    --reme-${p}: ${v};`).join('\n')}
  }
}

/* User-selected dark theme */
.dark {
${flatten(dark).map(([p, v]) => `  --reme-${p}: ${v};`).join('\n')}
}
`;
writeFileSync(join(dist, 'tokens.css'), css);

// shadcn-compatible theme keys for the components/ui/* layer (stock shadcn
// class names like `bg-card`, `text-muted-foreground`). Emitted as a Tailwind
// `@theme inline` block so Tailwind v4 actually mints those utilities —
// plain `:root` custom properties would not. globals.css imports this file
// instead of hand-listing the aliases; tokens/src/component.json
// "shadcnAlias" is the single source of truth.
const shadcnAlias = root.component.shadcnAlias ?? {};
const shadcnRefRe = /^\{semantic\.light\.([A-Za-z0-9.\-]+)\}$/;
const shadcnVar = (target, name) => {
  const m = typeof target === 'string' ? target.match(shadcnRefRe) : null;
  if (!m) {
    throw new Error(
      `shadcnAlias "${name}" must be a {semantic.light.…} reference (got ${JSON.stringify(target)})`,
    );
  }
  return m[1].split('.').map(kebab).join('-');
};
const shadcnCss = `/* reme v4 compatibility aliases — GENERATED by tokens/scripts/build.mjs. Do not edit by hand.
   Source: tokens/src/component.json "shadcnAlias". Maps shadcn utility names onto semantic reme tokens. */
@theme inline {
${Object.entries(shadcnAlias)
  .map(([name, target]) => `  --color-${name}: var(--reme-${shadcnVar(target, name)});`)
  .join('\n')}
}
`;
writeFileSync(join(dist, 'shadcn-aliases.css'), shadcnCss);

const scss = flatten({ ...resolved.primitive, ...light, ...{ motion: resolved.motion }, component: resolved.component })
  .map(([p, v]) => `$reme-${p}: ${v};`)
  .join('\n') + '\n';
writeFileSync(join(dist, 'tokens.scss'), scss);

const ts = `// reme v4 compatibility tokens — GENERATED by tokens/scripts/build.mjs. Do not edit by hand.
export const primitive = ${JSON.stringify(resolved.primitive, null, 2)} as const;
export const semanticLight = ${JSON.stringify(light, null, 2)} as const;
export const semanticDark = ${JSON.stringify(dark, null, 2)} as const;
export const motion = ${JSON.stringify(resolved.motion, null, 2)} as const;
export const component = ${JSON.stringify(resolved.component, null, 2)} as const;
export const tokens = { primitive, semanticLight, semanticDark, motion, component } as const;
export type Tokens = typeof tokens;
`;
writeFileSync(join(dist, 'tokens.ts'), ts);
writeFileSync(join(dist, 'tokens.json'), JSON.stringify(resolved, null, 2) + '\n');

// Video (Remotion/Hyperframes) consumer outputs — §44: motion/video MUST use
// generated tokens. tokens.video.json is the machine-readable contract;
// tokens.video.css exposes the same values as CSS custom properties for the
// static HTML compositions under videos/*/compositions.
const video = {
  color: {
    canvas: light['canvas'], surface: light['surface'], 'surface-subtle': light['surface-subtle'],
    'text-primary': light['text-primary'], 'text-secondary': light['text-secondary'],
    action: light['action'], focus: light['focus'],
  },
  surface: { background: light['surface'], raised: light['surface-raised'] ?? light['surface'] },
  text: { primary: light['text-primary'], secondary: light['text-secondary'], onAction: resolved.primitive.color['neutral-0'] ?? '#FFFFFF' },
  font: {
    latin: resolved.primitive.typography.family,
  },
  motion: resolved.motion,
  layout: resolved.primitive.layout,
};
writeFileSync(join(dist, 'tokens.video.json'), JSON.stringify(video, null, 2) + '\n');
const videoCss = `/* reme v4 compatibility video tokens — GENERATED by tokens/scripts/build.mjs. Do not edit by hand.
   Consumed by videos/* (Hyperframes compositions, Remotion players) via videos/shared/reme-tokens.mjs. */
:root {
${flatten({ color: video.color, font: { latin: video.font.latin }, motion: video.motion, layout: video.layout }).map(([p, v]) => `  --reme-video-${p}: ${v};`).join('\n')}
}
`;
writeFileSync(join(dist, 'tokens.video.css'), videoCss);

console.log(`tokens: built → tokens/generated/ (${Object.keys(resolved).join(', ')}, video)`);
