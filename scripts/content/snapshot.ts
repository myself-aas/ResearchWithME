import { readFileSync, writeFileSync } from 'node:fs';
import { loadPosts } from '../../lib/content/load';

const destination = 'lib/content/snapshot.generated.ts';
const content = `// GENERATED by npm run content:gen. Do not edit.\nimport type { Post } from './types';\nexport const publishedPosts: Post[] = ${JSON.stringify(loadPosts({ includeDrafts: false }), null, 2)};\n`;
if (process.argv.includes('--verify')) {
  if (readFileSync(destination, 'utf8') !== content) throw new Error(`Stale ${destination}; run npm run content:gen.`);
  console.log('PASS published content snapshot: current, deterministic, and draft-free.');
} else {
  writeFileSync(destination, content);
  console.log(`Generated ${destination} (${Buffer.byteLength(content)} bytes).`);
}
